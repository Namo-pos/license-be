-- ============================================================================
-- NOMA POS Supabase Migration Script
-- Tables: LICENSE and USER (PostgreSQL / Supabase)
-- ============================================================================

-- 1. Create LICENSE Table
CREATE TABLE IF NOT EXISTS "LICENSE" (
    "LICENSE_ID" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "LICENSE_CODE" VARCHAR(100) NOT NULL UNIQUE,
    "PLAN_TYPE" VARCHAR(50) NOT NULL DEFAULT 'FREE', -- 'FREE', 'PRO', 'ENTERPRISE'
    "LICENSE_JSON" JSONB NOT NULL,
    "IS_ACTIVE" BOOLEAN NOT NULL DEFAULT TRUE,
    "CREATED_AT" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UPDATED_AT" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Index for fast lookup by LICENSE_CODE and PLAN_TYPE
CREATE INDEX IF NOT EXISTS "IDX_LICENSE_CODE" ON "LICENSE"("LICENSE_CODE");
CREATE INDEX IF NOT EXISTS "IDX_LICENSE_PLAN_TYPE" ON "LICENSE"("PLAN_TYPE");

-- 2. Create USER Table
CREATE TABLE IF NOT EXISTS "USER" (
    "USER_ID" UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    "USERNAME" VARCHAR(100) NOT NULL UNIQUE,
    "PASSWORD" VARCHAR(255) NOT NULL,
    "MASTER_KEY" VARCHAR(150) NOT NULL, -- Autogenerated key for login feature
    "LICENSE_ID" UUID NOT NULL REFERENCES "LICENSE"("LICENSE_ID") ON DELETE CASCADE,
    "ROLE" VARCHAR(50) NOT NULL DEFAULT 'ADMIN',
    "CREATED_AT" TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    "UPDATED_AT" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Index for fast lookup by USERNAME, MASTER_KEY and LICENSE_ID
CREATE INDEX IF NOT EXISTS "IDX_USER_USERNAME" ON "USER"("USERNAME");
CREATE INDEX IF NOT EXISTS "IDX_USER_MASTER_KEY" ON "USER"("MASTER_KEY");
CREATE INDEX IF NOT EXISTS "IDX_USER_LICENSE_ID" ON "USER"("LICENSE_ID");

-- Optional: Comments for documentation
COMMENT ON TABLE "LICENSE" IS 'Stores subscription license records and configuration JSON (FREE, PRO, ENTERPRISE)';
COMMENT ON TABLE "USER" IS 'Stores licensed administrative users linked to their respective license with MASTER_KEY';
